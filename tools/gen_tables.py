"""Fixed-point tables for GR!MM's engines and effects (dsp.c, analog.c, fm6_core.c, hall.c, tape.c), no float on the target.

The part of Felucca's tools/gen_tables.py (hugelton/Felucca) its ANALOG engine needs: the pitch table, the filter's
cutoff curve and SVF coefficients, the soft clip, and the envelope steps (here two fixed times instead of Felucca's
0..127 tables), plus GR!MM's SUPERSAW detune offsets. FS = 44100 Hz, the control rate every CTL (32) frames.

  python3 tools/gen_tables.py firmware/gen/analog_tables.h
"""
import math
import sys
from pathlib import Path

FS = 44100
CTL = 32
ATTACK_MS = 3000        # GR!MM's drone envelope: a linear attack ...
RELEASE_MS = 6000       # ... and an exponential release, ~99 % of the way down after this


def arr(name, ctype, vals, per=12):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def main(path):
    L = ["/* generated by tools/gen_tables.py: do not edit */", "#pragma once", "#include <stdint.h>", ""]
    # phase increment for pitch in 1/16 semitone, MIDI 0..127 (Felucca's, bit for bit)
    inc = []
    for p in range(128 * 16):
        f = 440.0 * 2 ** ((p / 16 - 69) / 12)
        inc.append(min(int(f / FS * 2 ** 32), 0x7FFFFFFF))
    oct_ = inc[1856:2048]
    assert all(inc[q] == oct_[(q + 64) % 192] >> (10 - (q + 64) // 192) for q in range(2048))
    assert all((q + 64) * 21846 >> 22 == (q + 64) // 192 for q in range(2048))
    L += arr("PITCH_OCT", "uint32_t", oct_, 8)
    L += ["/* phase increment of pitch p in 1/16 semitone, 0..2047 (MIDI 0..127): 440 Hz * 2^((p / 16 - 69) / 12) */",
          "static inline uint32_t pitch_inc(uint32_t p)",
          "{",
          "    uint32_t i = p + 64u, o = (i * 21846u) >> 22;     /* i / 192: the octave above PITCH_OCT's - 10 */",
          "    return PITCH_OCT[i - o * 192u] >> (10u - o);",
          "}"]
    # envelope (Felucca's formulas for ENV_LIN / ENV_EXP, at GR!MM's two times)
    atk = max(1, int((1 << 24) * CTL / (ATTACK_MS * FS / 1000)))
    tau = RELEASE_MS / 1000 / 4.6
    rel = max(1, min(65535, int(65536 * (1 - math.exp(-CTL / (tau * FS))))))
    L += [f"#define ENV_ATK_STEP {atk}   /* Q24 a control step: 0 -> 1 in {ATTACK_MS} ms */",
          f"#define ENV_REL_K {rel}        /* Q16 a control step: ~99 % down after {RELEASE_MS} ms */"]
    # filter cutoff 30 Hz .. 16 kHz, and the trapezoidal (Simper) SVF's g = tan(pi fc / FS), Q12
    fc = [30.0 * ((16000 / 30) ** (v / 127)) for v in range(128)]
    L += arr("CUTOFF_HZ", "uint16_t", [int(round(f)) for f in fc])
    L += arr("SVF_G", "uint16_t", [int(4096 * math.tan(math.pi * min(f, 0.45 * FS) / FS)) for f in fc])
    # soft clip curve for |x| in 0..2 (Q12 in, Q15 out): tanh
    L += arr("TANH_Q15", "int16_t", [int(32767 * math.tanh(i / 256 * 2)) for i in range(257)])
    # SUPERSAW (GR!MM): the seven saws' frequency offsets at full DETUNE, Q15 of the pitch (Adam Szabo's measurements
    # of the JP-8000's supersaw, "How to Emulate the Super Saw", 2010); the middle one is the note itself
    off = [-0.11002313, -0.06288439, -0.01952356, 0.0, 0.01991221, 0.06216538, 0.10745242]
    L += arr("SSAW_OFF_Q15", "int16_t", [int(round(o * 32768)) for o in off])
    # SPACE (firmware/src/hall.c, after Felucca's HALL): RT60 = 0.4 s * 2^(SIZE / 20) for SIZE 0..126 (0.4 .. ~32 s;
    # Felucca's 0.5 s * 2^(SIZE / 30), 0.5 .. 9 s), 127 = INF. A line of D samples (22.05 kHz) loses 60 dB in
    # RT60 * 22050 / D passes: g = 10^(-3 D / (22050 RT60)); over sqrt(7) (the 8 x 8 matrix's rows: 7 entries of +-1),
    # Q14. INF: the matrix lossless but for 1e-4 a pass (6192: ~1 dB a minute)
    lens = [853, 941, 1031, 1123, 1237, 1361, 1493, 1637]
    rt = [0.4 * 2 ** (s / 20) for s in range(127)]
    g = [[int(round(16384 / math.sqrt(7) * min(0.999, 10 ** (-3 * d / (22050 * t))))) for d in lens] for t in rt]
    g.append([6192] * len(lens))
    L += [f"static const int16_t RV_G[128][{len(lens)}] = {{"]
    L += ["    {" + ", ".join(str(v) for v in row) + "}," for row in g]
    L += ["};"]
    L += arr("RV_RT60_X10", "uint16_t", [int(round(t * 10)) for t in rt])
    # DELAY (firmware/src/tape.c): TIME 0..127 -> 20 .. 3500 ms, exponential (~700 ms at 88)
    L += arr("DL_MS", "uint16_t", [int(round(20 * 175 ** (v / 127))) for v in range(128)])
    # FM (firmware/src/fm6_core.c, msfa via Felucca): Felucca's sine (1025 points: SINE[i + 1] needs no wrap) and its
    # FM6 tables (fm6_tables below: Felucca's tools/gen_tables.py, as it is)
    L += arr("SINE", "int16_t", [int(round(32767 * math.sin(2 * math.pi * i / 1024))) for i in range(1025)])
    L += fm6_tables()
    Path(path).write_text("\n".join(L) + "\n")
    print(f"tables: {path}")


