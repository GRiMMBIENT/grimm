"""GR!MM's screen font: Press Start 2P (assets/fonts/PressStart2P-Regular.ttf, SIL Open Font License 1.1, the Press
Start 2P Project Authors; LICENSES/OFL-PressStart2P.txt) rasterised at its native 8 px grid into bitmaps, ASCII 32..126,
8 x 8, a byte a row (bit 7 = the left pixel) -> firmware/gen/grimm_pixfont.h. Under the OFL a format conversion is a
Modified Version, so GR!MM calls it "pixfont", not by the font's Reserved Font Name.

  python3 tools/gen_pixfont.py          (needs Pillow)
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
TTF = ROOT / "assets" / "fonts" / "PressStart2P-Regular.ttf"
OUT = ROOT / "firmware" / "gen" / "grimm_pixfont.h"


def main():
    font = ImageFont.truetype(str(TTF), 8)
    rows = []
    for ch in range(32, 127):
        im = Image.new("L", (16, 16), 0)
        ImageDraw.Draw(im).text((0, 0), chr(ch), font=font, fill=255)
        g = []
        for y in range(8):
            b = 0
            for x in range(8):
                if im.getpixel((x, y)) >= 128:
                    b |= 0x80 >> x
            g.append(b)
        rows.append((ch, g))
    out = ["/* generated by tools/gen_pixfont.py: GR!MM's pixfont, Press Start 2P (SIL OFL 1.1, the Press Start 2P",
           " * Project Authors) rasterised at its 8 px grid; ASCII 32..126, 8 rows a glyph, bit 7 = the left pixel */",
           "static const uint8_t PIXFONT[95][8] = {"]
    for ch, g in rows:
        c = chr(ch).replace("\\", "\\\\").replace("*", "*")
        out.append("    {" + ", ".join(f"0x{b:02X}" for b in g) + "},   /* " + (c if c not in "*/" else "'" + c + "'") + " */")
    out.append("};")
    OUT.write_text("\n".join(out) + "\n")
    print(f"{OUT.relative_to(ROOT)}: {len(rows)} glyphs")


if __name__ == "__main__":
    main()
