"""GR!MM's factory samples: assets/samples/*.wav (GR!MM's recordings, CC0 1.0) as the four sample slots hold
them, made exactly as tools/fm1_sample_upload.py uploads a WAV (its build(): 22050 Hz mono, IMA ADPCM, cut to 6.64 s
with a 20 ms fade, the "GSMP" header), into firmware/gen/grimm_samples.h. samples.c writes one into a slot that is
erased at power-on, and all four on RESTORE (SYSTEM 2, the editor page).

  py tools/gen_samples.py          (needs nothing but Python 3; the same bytes every time)
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import fm1_sample_upload as up  # noqa: E402

SAMPLES = [("Urchin.wav", "URCHIN"), ("Leave.wav", "LEAVE"), ("Nikolai.wav", "NIKOLAI"), ("M-Soft.wav", "M-SOFT")]
ROOT_NOTE = 60                                  # C4, as an upload without a note in its name


def carray(name, b):
    lines = [",".join(str(x) for x in b[i:i + 40]) for i in range(0, len(b), 40)]
    return f"static const uint8_t {name}[{len(b)}] = {{\n" + ",\n".join(lines) + "};\n"


def main():
    out = ["/* Generated by tools/gen_samples.py from assets/samples/ (do not edit). GR!MM's factory samples:",
           " * Copyright (C) 2026 GR!MM, CC0 1.0 (LICENSES/CC0-1.0.txt). Each one as a slot holds it",
           " * (samples.c): the 480-byte header, then the IMA ADPCM data written at 512. */",
           "#define SMP_FACT_N 4u"]
    for k, (wav, name) in enumerate(SAMPLES):
        hdr, data, secs, cut = up.build(ROOT / "assets" / "samples" / wav, name, ROOT_NOTE)
        print(f"slot {k + 1}: {wav} -> {name}, {secs:.2f} s{' (cut)' if cut else ''}, {len(data)} B")
        out.append(f"/* slot {k + 1}: {name}, {wav}, {secs:.2f} s */")
        out.append(carray(f"SMP_FH{k}", hdr) + carray(f"SMP_FD{k}", data))
    out.append("static const uint8_t *const SMP_FACT_HDR[SMP_FACT_N] = {" + ", ".join(f"SMP_FH{k}" for k in range(4)) + "};")
    out.append("static const uint8_t *const SMP_FACT_DATA[SMP_FACT_N] = {" + ", ".join(f"SMP_FD{k}" for k in range(4)) + "};")
    out.append("static const uint32_t SMP_FACT_LEN[SMP_FACT_N] = {" + ", ".join(f"sizeof SMP_FD{k}" for k in range(4)) + "};")
    path = ROOT / "firmware" / "gen" / "grimm_samples.h"
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"{path.relative_to(ROOT)}: {path.stat().st_size} B")


if __name__ == "__main__":
    main()
