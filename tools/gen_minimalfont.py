"""GR!MM's MINIMAL theme fonts -> firmware/gen/minimal_font.h: Terminus Regular 6x12 and 8x14 (the ASCII part of Terminus Font's medium cuts, assets/fonts/terminus-regular:
tools/gen_terminus_regular.py; SIL OFL 1.1, Dimitar Toshkov Zhekov: assets/fonts/Terminus-LICENSE.txt), the same format as the bold ones in brutal_font.h (a byte a row, the left
pixel the top bit, ASCII 32..126); the bold cuts are the BRUTAL theme's (brutal term). Under the OFL a format conversion is a Modified Version: GR!MM calls these "minimal term".
  python3 tools/gen_minimalfont.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_brutalfont import ROOT, bdf  # noqa: E402

REG = ROOT / "assets" / "fonts" / "terminus-regular"
OUT = ROOT / "firmware" / "gen" / "minimal_font.h"
lines = ["/* generated by tools/gen_minimalfont.py: GR!MM's MINIMAL fonts. minimal term: Terminus Regular (SIL OFL 1.1, Dimitar Toshkov Zhekov) 6x12, 8x14, ASCII 32..126, a byte a row,",
         " * the left pixel the top bit; the bold cuts are brutal_font.h's (br_tfont_t). */"]
total = 0
for name, fn in (("12R", "ter-u12n-ascii.bdf"), ("14R", "ter-u14n-ascii.bdf")):
    cw, chh, cells = bdf(REG / fn)
    data = bytearray()
    for c in range(32, 127):
        data += bytes(cells[c])
    hrows = [i for i, b in enumerate(cells[ord("H")]) if b]
    lines.append(f"static const uint8_t BRT{name}_DATA[] = {{")
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"static const br_tfont_t BRT{name} = {{{cw}, {chh}, {hrows[0]}, {len(hrows)}, BRT{name}_DATA}};")
    total += len(data)
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{OUT}: {total} B")
