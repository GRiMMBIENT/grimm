"""GR!MM's FM patches (firmware/src/fm.c) -> a C header of 155-byte voices.

  python3 tools/gen_fm_patches.py firmware/gen/grimm_fm.h

GR!MM's own patches, written here for it (no factory data of any instrument, and none of Felucca's F1..F8): drones,
so every carrier sustains (GR!MM's own 3 s / 6 s envelope sits on top). The layout is the generic 155-byte
6-operator voice that msfa (firmware/src/fm6_core.c) reads: 6 x 21 operator bytes (the sixth operator first), then
the pitch envelope, algorithm, feedback, LFO, transpose and a 10-character name.

Per operator: rates r and levels l of its envelope (0..99, 99 = fastest / loudest), output level ol (0..99), ratio
mode (coarse fc 0..31, 0 = 0.5; fine ff 0..99: ratio = fc * (1 + ff / 100)), detune det (0..14, 7 = none).
"""
import sys
from pathlib import Path


def op(ol, fc=1, ff=0, det=7, r=(99, 99, 99, 60), l=(99, 99, 99, 0), kvs=0, rs=0):
    #       R1..R4      L1..L4      BP  LD RD LC RC RS  AMS KVS  OL  MODE FC  FF  DET
    return list(r) + list(l) + [39, 0, 0, 0, 0, rs, 0, kvs, ol, 0, fc, ff, det]


def voice(name, alg, ops, fb=0, lfs=35, lpmd=0, lfw=4, lpms=0, trnsp=24):
    """ops: OP1..OP6; alg 1..32"""
    assert len(ops) == 6 and 1 <= alg <= 32 and len(name) <= 10
    v = []
    for o in reversed(ops):                        # stored OP6 .. OP1
        assert len(o) == 21
        v += o
    #     PR1..PR4        PL1..PL4        ALG      FB  OKS LFS  LFD LPMD  LAMD LKS LFW  LPMS  TRNSP
    v += [99] * 4 + [50] * 4 + [alg - 1, fb, 1, lfs, 0, lpmd, 0, 0, lfw, lpms, trnsp]
    v += [ord(c) for c in name.ljust(10)]
    assert len(v) == 155 and all(0 <= x < 128 for x in v)
    return v


# algorithm 5: three pairs (OP1 <- OP2, OP3 <- OP4, OP5 <- OP6, the feedback on OP6); 32: six carriers (feedback on
# OP6); 1: OP1 <- OP2 and OP3 <- OP4 <- OP5 <- OP6 (the feedback on OP6)
PATCHES = [
    voice("BELL", 5, [                             # inharmonic pairs: 1 by 4.5, 2 by 5.6, a hum (0.5) by 1.41
        op(99, r=(99, 28, 20, 35), l=(99, 88, 82, 0)),
        op(74, fc=3, ff=50, r=(99, 30, 22, 35), l=(99, 72, 58, 0)),
        op(90, fc=2, det=9, r=(99, 24, 18, 35), l=(99, 86, 78, 0)),
        op(64, fc=5, ff=12, r=(99, 34, 24, 35), l=(99, 66, 50, 0)),
        op(84, fc=0, det=6, r=(99, 20, 15, 35), l=(99, 90, 86, 0)),
        op(52, fc=1, ff=41, r=(99, 40, 30, 35), l=(99, 60, 44, 0))]),
    voice("ORGAN", 32, [                           # drawbars: 0.5 1 2 3 4, and a 1 with feedback for the bite
        op(78, fc=0),
        op(84),
        op(76, fc=2),
        op(66, fc=3),
        op(62, fc=4),
        op(58)],
        fb=4, lfs=34, lpmd=6, lpms=2),
    voice("SOFT PAD", 5, [                         # gently modulated, detuned carriers; the modulators swell in
        op(88, det=6, r=(60, 50, 99, 50)),
        op(62, r=(40, 30, 99, 50), l=(99, 85, 85, 0)),
        op(84, det=10, r=(60, 50, 99, 50)),
        op(55, fc=2, r=(35, 30, 99, 50), l=(99, 80, 80, 0)),
        op(74, fc=2, det=4, r=(60, 50, 99, 50)),
        op(48, r=(30, 30, 99, 50), l=(99, 80, 80, 0))],
        fb=2, lfs=20, lpmd=4, lpms=2),
    voice("REED", 1, [                             # a buzzy stack: OP3 by 3 by 1 by 1 with feedback, beside 1 by 1
        op(90),
        op(70),
        op(78, det=9),
        op(58, fc=3),
        op(54),
        op(50)],
        fb=5, lfs=30, lpmd=5, lpms=2),
]


def main(path):
    L = ["/* generated by tools/gen_fm_patches.py: do not edit */", "#pragma once", "#include <stdint.h>", "",
         f"#define FM_NPATCH {len(PATCHES)}",
         "static const uint8_t FM_PATCH[FM_NPATCH][155] = {"]
    for v in PATCHES:
        L.append("    {" + ", ".join(str(x) for x in v) + "},")
    L += ["};", "static const char *const FM_PATCH_NAME[FM_NPATCH] = {" +
          ", ".join('"' + bytes(v[145:155]).decode().rstrip() + '"' for v in PATCHES) + "};"]
    Path(path).write_text("\n".join(L) + "\n")
    print(f"fm patches: {path}")


if __name__ == "__main__":
    main(sys.argv[1])
